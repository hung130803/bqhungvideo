function Kiem-App-Dang-Chay {
    $ds = @()
    try {
        $ds = Get-CimInstance Win32_Process | Where-Object {
            ($_.ExecutablePath -and $_.ExecutablePath.StartsWith($Goc, [System.StringComparison]::OrdinalIgnoreCase)) -or
            ($_.Name -match '^(python|pythonw)\.exe$' -and $_.CommandLine -like "*$TenDA*") -or
            ($_.Name -eq 'BQHungVideo.exe')
        }
    } catch { }
    return $ds
}

function Chuyen-Rac {
    $dang = Kiem-App-Dang-Chay
    if ($dang) {
        Write-Host ''
        Write-Host '  App (hoặc script Python của dự án) ĐANG CHẠY. Hãy tắt hẳn rồi chạy lại.' -ForegroundColor Red
        $dang | ForEach-Object { Write-Host ('    PID ' + $_.ProcessId + '  ' + $_.Name) }
        return
    }
    $gio = Get-Date -Format 'yyyyMMdd_HHmmss'
    $Rac = Join-Path $Cha ("_RAC_" + $TenDA + "_" + $gio)
    New-Item -ItemType Directory -Path $Rac -Force | Out-Null
    $log = Join-Path $Rac '_NHAT_KY.txt'
    "Chuyển từ: $Goc" | Out-File -FilePath $log -Encoding utf8
    $ok = 0; $vang = 0; $loi = 0
    foreach ($ten in $DanhSach) {
        $nguon = Join-Path $Goc $ten
        if (-not (Test-Path -LiteralPath $nguon)) { $vang++; continue }
        try {
            Move-Item -LiteralPath $nguon -Destination (Join-Path $Rac $ten) -Force
            "MOVED`t$ten" | Out-File -FilePath $log -Append -Encoding utf8
            $ok++
        } catch {
            "FAIL`t$ten`t$($_.Exception.Message)" | Out-File -FilePath $log -Append -Encoding utf8
            Write-Host ("  Không chuyển được: " + $ten + " — " + $_.Exception.Message) -ForegroundColor Yellow
            $loi++
        }
    }
    # BẢN APP CŨ do các lần tự cập nhật bỏ lại trong D:\BQHungVideo (app KHÔNG đọc lại
    # chúng — update_swap chỉ cất vào rồi thôi). Giữ lại bản do công cụ cập nhật của
    # Claude cất gần nhất để còn quay lại được.
    $AppDir = 'D:\BQHungVideo'
    if (Test-Path -LiteralPath $AppDir) {
        $giu = Get-ChildItem -LiteralPath $AppDir -Directory -Force -Filter '.update-backup-claude-*' | Sort-Object Name -Descending | Select-Object -First 1
        $RacApp = Join-Path $Rac '_BQHungVideo_ban_cu'
        Get-ChildItem -LiteralPath $AppDir -Directory -Force | Where-Object {
            ($_.Name -like '.update-backup-*' -or $_.Name -like '.update-stage-*' -or $_.Name -like '.ban-moi-bo-*') -and
            (-not $giu -or $_.FullName -ne $giu.FullName)
        } | ForEach-Object {
            if (-not (Test-Path $RacApp)) { New-Item -ItemType Directory -Path $RacApp | Out-Null }
            try {
                Move-Item -LiteralPath $_.FullName -Destination (Join-Path $RacApp $_.Name) -Force
                "MOVED`tD:\BQHungVideo\$($_.Name)" | Out-File -FilePath $log -Append -Encoding utf8
                $ok++
            } catch {
                "FAIL`tD:\BQHungVideo\$($_.Name)`t$($_.Exception.Message)" | Out-File -FilePath $log -Append -Encoding utf8
                $loi++
            }
        }
    }
    Write-Host ''
    Write-Host ("  Đã chuyển $ok mục ra: $Rac") -ForegroundColor Green
    if ($vang) { Write-Host ("  ($vang mục không còn trên máy — bỏ qua)") }
    if ($loi)  { Write-Host ("  $loi mục đang bị khoá, xem _NHAT_KY.txt") -ForegroundColor Yellow }
    Write-Host ''
    Write-Host '  BÂY GIỜ: mở app (run.bat), làm thử 1 video. Ổn thì chạy lại DON_DEP.bat'
    Write-Host '  và chọn 3 để xoá hẳn. Có vấn đề thì chọn 2 để hoàn tác.'
}

function Lay-Thu-Muc-Rac {
    Get-ChildItem -LiteralPath $Cha -Directory -Filter ("_RAC_" + $TenDA + "_*") |
        Sort-Object Name -Descending
}

function Hoan-Tac {
    $rac = Lay-Thu-Muc-Rac | Select-Object -First 1
    if (-not $rac) { Write-Host '  Không có gì để hoàn tác.'; return }
    $n = 0
    $RacApp = Join-Path $rac.FullName '_BQHungVideo_ban_cu'
    if (Test-Path -LiteralPath $RacApp) {
        Get-ChildItem -LiteralPath $RacApp -Force | ForEach-Object {
            $dich = Join-Path 'D:\BQHungVideo' $_.Name
            if (-not (Test-Path -LiteralPath $dich)) { Move-Item -LiteralPath $_.FullName -Destination $dich; $n++ }
        }
        if (@(Get-ChildItem -LiteralPath $RacApp -Force).Count -eq 0) { Remove-Item -LiteralPath $RacApp -Force }
    }
    Get-ChildItem -LiteralPath $rac.FullName -Force | Where-Object { $_.Name -ne '_NHAT_KY.txt' } | ForEach-Object {
        $dich = Join-Path $Goc $_.Name
        if (Test-Path -LiteralPath $dich) {
            Write-Host ("  Bỏ qua (đã có ở dự án): " + $_.Name) -ForegroundColor Yellow
        } else {
            Move-Item -LiteralPath $_.FullName -Destination $dich; $n++
        }
    }
    Write-Host ("  Đã trả $n mục về $Goc") -ForegroundColor Green
    $con = @(Get-ChildItem -LiteralPath $rac.FullName -Force | Where-Object { $_.Name -ne '_NHAT_KY.txt' })
    if ($con.Count -eq 0) { Remove-Item -LiteralPath $rac.FullName -Recurse -Force }
}

function Xoa-Han {
    $ds = @(Lay-Thu-Muc-Rac)
    if ($ds.Count -eq 0) { Write-Host '  Chưa có thư mục rác nào (hãy chạy bước 1 trước).'; return }
    $ds | ForEach-Object { Write-Host ('  ' + $_.FullName) }
    $tl = Read-Host '  XOÁ VĨNH VIỄN các thư mục trên? Gõ XOA để đồng ý'
    if ($tl -ne 'XOA') { Write-Host '  Đã huỷ, không xoá gì.'; return }
    foreach ($d in $ds) {
        Write-Host ('  Đang xoá ' + $d.Name + ' (thư mục lớn có thể mất vài phút)...')
        Remove-Item -LiteralPath $d.FullName -Recurse -Force
    }
    Write-Host '  Xong.' -ForegroundColor Green
}

